#[test]
fn test_handle_plan_command_case_insensitivity() {
    let (_, dag) = handle_goal_command("Build caching layer");

    let status_lower = handle_plan_command(&["status".to_string()], Some(&dag));
    let status_upper = handle_plan_command(&["STATUS".to_string()], Some(&dag));
    let status_mixed = handle_plan_command(&["StAtUs".to_string()], Some(&dag));
    assert_eq!(status_lower, status_upper);
    assert_eq!(status_lower, status_mixed);

    let cancel_lower = handle_plan_command(&["cancel".to_string()], Some(&dag));
    let cancel_upper = handle_plan_command(&["CANCEL".to_string()], Some(&dag));
    assert_eq!(cancel_lower, cancel_upper);
}

#[test]
fn test_handle_plan_command_whitespace_tolerance() {
    let (_, dag) = handle_goal_command("Build caching layer");

    let status_clean = handle_plan_command(&["status".to_string()], Some(&dag));
    let status_padded = handle_plan_command(&["   status   ".to_string()], Some(&dag));
    assert_eq!(status_clean, status_padded);

    let stages_clean = handle_plan_command(&["stages".to_string()], Some(&dag));
    let stages_padded = handle_plan_command(&["\tstages\n".to_string()], Some(&dag));
    assert_eq!(stages_clean, stages_padded);
}

