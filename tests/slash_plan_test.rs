#[test]
fn test_handle_goal_command_basic() {
    let prompt = "Implement user authentication with JWT and refresh tokens";
    let (preview, dag) = handle_goal_command(prompt);

    // Verify DAG metadata
    assert_eq!(dag.goal, prompt);
    assert!(dag.name.starts_with("Plan: "));
    assert!(dag.name.contains("Implement user authentication"));
    assert!(!dag.id.is_empty());

    // Verify tasks generated by standard feature strategy
    assert!(dag.task_count() >= 4);
    assert!(dag.tasks.contains_key("scout_arch"));
    assert!(dag.tasks.contains_key("coder_core") || dag.tasks.contains_key("coder_feature"));
    assert!(dag.tasks.contains_key("tester_integration"));

    // Verify stages were computed
    assert!(!dag.stages.is_empty());

    // Verify preview output
    assert!(preview.contains("DAG Plan:"));
    assert!(preview.contains(&dag.name));
    assert!(preview.contains(&dag.id));
    assert!(preview.contains(prompt));
    assert!(preview.contains("Overall Status:"));
    assert!(preview.contains("scout_arch"));
}

