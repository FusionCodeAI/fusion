#[test]
fn test_handle_goal_command_roles_and_dependencies() {
    let (preview, dag) = handle_goal_command("Refactor config parser to use TOML and YAML");

    // Scout role check
    let scout = dag.get_task("scout_arch").expect("scout_arch task");
    assert_eq!(scout.role, SubagentRole::Scout);
    assert!(scout.dependencies.is_empty());

    // Core coder check
    if let Some(coder) = dag.get_task("coder_core") {
        assert_eq!(coder.role, SubagentRole::Coder);
        assert!(coder.dependencies.contains(&"scout_arch".to_string()));
    }

    // Tester check
    if let Some(tester) = dag.get_task("tester_integration") {
        assert_eq!(tester.role, SubagentRole::Tester);
    }

    // Preview contains roles
    assert!(preview.contains("Scout"));
}

